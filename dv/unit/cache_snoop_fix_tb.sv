    acvalid=1; acaddr=44'h0000_0000_040; acsnoop=ARSNOOP_READ_SHARED;
    #1;
    if(acready!==1'b1)
      $fatal(1,"CACHE_SNOOP_REGRESSION_FAIL A blocked an earlier AC while AW waited for READY");
    $display("CACHE_SNOOP_SUBTEST_PASS A_AC_ORDER"); $finish;
